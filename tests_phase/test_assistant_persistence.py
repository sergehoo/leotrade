@pytest.mark.django_db
def test_api_archive_delete_and_isolation(client, user):
    from django.contrib.auth import get_user_model

    client.force_login(user)
    conversation = _seed_conversation(user)

    # Archive (toggle)
    resp = client.post(f"/assistant/api/conversations/{conversation.id}/archive/")
    assert resp.json()["archived"] is True
    # La liste par défaut exclut les archivées
    assert client.get("/assistant/api/conversations/").json()["count"] == 0
    assert client.get("/assistant/api/conversations/?archived=true").json()["count"] == 1

    # Isolation : un autre utilisateur ne voit rien et ne peut rien supprimer
    other = get_user_model().objects.create_user(username="other2", password="x")
    client.force_login(other)
    assert client.get("/assistant/api/conversations/?archived=all").json()["count"] == 0
    assert client.delete(f"/assistant/api/conversations/{conversation.id}/").status_code == 404

    # Suppression par le propriétaire
    client.force_login(user)
    assert client.delete(f"/assistant/api/conversations/{conversation.id}/").status_code == 204
    assert not AssistantConversation.objects.filter(pk=conversation.id).exists()


