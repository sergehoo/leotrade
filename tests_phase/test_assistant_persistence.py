@pytest.mark.django_db
def test_stale_partial_marked_failed(user):
    from datetime import timedelta

    from ai_assistant.tasks import mark_stale_partials_task

    conversation = ConversationService.get_or_create_for_context(user, {})
    message = AssistantMessage.objects.create(
        conversation=conversation, role="ASSISTANT",
        content="texte partiel sauvegardé", status="PARTIAL",
    )
    AssistantMessage.objects.filter(pk=message.pk).update(
        updated_at=timezone.now() - timedelta(minutes=30),
    )

    result = mark_stale_partials_task()

    assert result == {"marked_failed": 1}
    message.refresh_from_db()
    assert message.status == "FAILED"
    assert message.content == "texte partiel sauvegardé"
