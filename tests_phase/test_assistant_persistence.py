@pytest.mark.django_db
def test_each_context_gets_independent_conversation(user):
    general = ConversationService.get_or_create_for_context(user, {"page": "opportunities"})
    idea = ConversationService.get_or_create_for_context(user, {"trade_idea_id": 145})
    position = ConversationService.get_or_create_for_context(user, {"position_id": 25})
    dashboard = ConversationService.get_or_create_for_context(user, {"page": "dashboard"})

    assert general.context_type == "GENERAL"
    assert (idea.context_type, idea.context_id) == ("TRADE_IDEA", 145)
    assert (position.context_type, position.context_id) == ("POSITION", 25)
    assert dashboard.context_type == "DASHBOARD"
    assert len({general.id, idea.id, position.id, dashboard.id}) == 4

    # Même contexte → même conversation (pas de doublon)
    again = ConversationService.get_or_create_for_context(user, {"trade_idea_id": "145"})
    assert again.id == idea.id

    # Le créateur est enregistré comme participant OWNER (futur mode équipe)
    assert AssistantConversationParticipant.objects.filter(
        conversation=idea, user=user, role="OWNER",
    ).exists()


