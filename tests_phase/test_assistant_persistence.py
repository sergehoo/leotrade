def _seed_conversation(user, *, title="Conv R_75", content="Le R_75 monte"):
    conversation = ConversationService.get_or_create_for_context(user, {"trade_idea_id": 7})
    conversation.title = title
    conversation.save(update_fields=["title"])
    AssistantMessage.objects.create(conversation=conversation, role="USER", content=content)
    AssistantMessage.objects.create(
        conversation=conversation, role="ASSISTANT", content="Réponse IA",
        status="SAVED", provider="CLAUDE", model_name="claude-x",
        tokens_in=100, tokens_out=50,
    )
    return conversation


@pytest.mark.django_db
def test_api_list_search_and_filters(client, user):
    client.force_login(user)
    _seed_conversation(user)
    ConversationService.get_or_create_for_context(user, {"position_id": 3})

    resp = client.get("/assistant/api/conversations/")
    assert resp.status_code == 200
    assert resp.json()["count"] == 2

    resp = client.get("/assistant/api/conversations/?context_type=TRADE_IDEA")
    assert resp.json()["count"] == 1

    # Recherche plein texte (titre + contenu des messages)
    resp = client.get("/assistant/api/conversations/?q=R_75 monte")
    assert resp.json()["count"] == 1


