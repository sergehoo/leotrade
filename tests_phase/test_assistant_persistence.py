#  2. Génération détachée
# ─────────────────────────────────────────────────────────────────────────────

async def _fake_stream_ok(messages, system_prompt):
    for chunk in ["Bonjour, ", "voici mon ", "analyse complète."]:
        yield chunk


async def _fake_stream_crash(messages, system_prompt):
    yield "Début de réponse…"
    raise ConnectionError("provider down")


def _run_generation(conversation, user_text="analyse R_75"):
    placeholder = AssistantMessage.objects.create(
        conversation=conversation, role="ASSISTANT", content="", status="PARTIAL",
    )
    asyncio.run(AssistantGenerationService._run_safe(
        conversation.id, placeholder.id, user_text, {},
    ))
    placeholder.refresh_from_db()
    return placeholder


@pytest.mark.django_db(transaction=True)
def test_generation_saves_complete_response(user):
    conversation = ConversationService.get_or_create_for_context(user, {})
    AssistantMessage.objects.create(
        conversation=conversation, role="USER", content="analyse R_75",
    )

    with mock.patch(
        "ai_assistant.services.AssistantStreamService.stream",
        side_effect=_fake_stream_ok,
    ), mock.patch(
        "ai_assistant.services.AssistantContextService.build", return_value={},
    ):
        message = _run_generation(conversation)

    assert message.status == "SAVED"
    assert message.content == "Bonjour, voici mon analyse complète."
    # Quota consommé sur succès
    assert user.ai_quota.messages_used == 1


@pytest.mark.django_db(transaction=True)
def test_generation_failure_keeps_partial_content(user):
    conversation = ConversationService.get_or_create_for_context(user, {})
    AssistantMessage.objects.create(
        conversation=conversation, role="USER", content="analyse",
    )

    with mock.patch(
        "ai_assistant.services.AssistantStreamService.stream",
        side_effect=_fake_stream_crash,
    ), mock.patch(
        "ai_assistant.services.AssistantContextService.build", return_value={},
    ):
        message = _run_generation(conversation)

    assert message.status == "FAILED"
    assert "Début de réponse…" in message.content   # contenu partiel CONSERVÉ
    assert message.error_message == "provider_stream_error"
    # Pas de consommation de quota sur échec
    from ai_assistant.models import AIUserQuota
    quota = AIUserQuota.objects.filter(user=user).first()
    assert quota is None or quota.messages_used == 0


